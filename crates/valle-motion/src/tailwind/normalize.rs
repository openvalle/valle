/// Reject a utility that carries a variant prefix.
///
/// Balanced brackets, quotes, escapes and comments are scanned first so a colon *inside* an
/// arbitrary value (`[background:url(a:b)]`) is still part of the value. The signature is
/// deliberately narrower than the previous splitter: after the convergence there are no variants to
/// interpret, only this boundary to report.
fn reject_variants(candidate: &str) -> Result<&str, TailwindClassError> {
    let fail = || {
        TailwindClassError::Syntax(
            "utility variants and arbitrary values require balanced brackets, quotes and escapes",
        )
    };
    let mut stack = Vec::new();
    let mut quote = None;
    let mut escaped = false;
    let mut at_start = true;
    let mut chars = candidate.char_indices().peekable();
    while let Some((_, ch)) = chars.next() {
        if escaped {
            escaped = false;
            at_start = false;
            continue;
        }
        if ch == '\\' {
            escaped = true;
            continue;
        }
        if let Some(end) = quote {
            if ch == end {
                quote = None;
            }
            continue;
        }
        if ch == '/' && chars.peek().is_some_and(|(_, ch)| *ch == '*') {
            chars.next();
            let mut closed = false;
            while let Some((_, ch)) = chars.next() {
                if ch == '*' && chars.peek().is_some_and(|(_, ch)| *ch == '/') {
                    chars.next();
                    closed = true;
                    break;
                }
            }
            if !closed {
                return Err(fail());
            }
            continue;
        }
        match ch {
            '\'' | '"' => quote = Some(ch),
            '[' | '(' => {
                if stack.len() >= 64 {
                    return Err(fail());
                }
                stack.push(if ch == '[' { ']' } else { ')' });
            }
            ']' | ')' => {
                if stack.pop() != Some(ch) {
                    return Err(fail());
                }
            }
            ':' if stack.is_empty() => {
                if at_start {
                    return Err(fail());
                }
                return Err(TailwindClassError::Forbidden);
            }
            _ => {}
        }
        at_start = false;
    }
    if quote.is_some() || !stack.is_empty() {
        return Err(fail());
    }
    Ok(candidate)
}

