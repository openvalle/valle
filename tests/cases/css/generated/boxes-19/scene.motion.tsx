function Box({ node }) {
  return (
    <View key={node.key} style={node.style}>
      {node.children.map((child) => (
        <Box node={child} />
      ))}
    </View>
  );
}
export default function Scene() {
  return (
    <View style={{ width: 1600, height: 736, background: "white" }}>
      {TREES.map((node) => (
        <Box node={node} />
      ))}
    </View>
  );
}
